const getBikesByCategory = (category: BikeCategory): Bike[] => {
  return bikes.filter(bike => bike.category === category);
};

const getBikeById = (id: string): Bike | undefined => {
  return bikes.find(bike => bike.id === id);
};

const getFeaturedBikes = (): Bike[] => {
  const featuredBikeIds = ['classic-350', 'himalayan', 'r15-v4', 'activa-6g'];
  return featuredBikeIds
    .map(id => bikes.find(bike => bike.id === id))
    .filter((bike): bike is Bike => bike !== undefined);
};

